/**
 * Shared email scraping utility.
 * Scrapes websites and extracts email addresses.
 * Used by hr.component (API) and exelScrapingRoute (Google Sheets sync).
 *
 * Only extracts emails from: (1) explicit mailto: links in the HTML, (2) visible text in the website's raw HTML
 * (homepage, footer, header, contact pages). No JSON-LD or script content—only mailto and visible page source.
 * Scans: trusted sections (footer/header/contact), full page-source (visible HTML), then domain filter.
 * Only return emails that: valid syntax; match website domain; appear on the page (no inferred addresses).
 * Ignore: image filenames; internal aliases; random codes. Normalize duplicates; include verifiedCount.
 * If emails exist but require JS rendering → output: "Emails present but require JS rendering".
 * For JS-rendered or captcha-protected sites (e.g. upkeepdxb.com): when static fetch finds no email,
 * browser automation is used: Playwright is tried first for captcha/challenge sites, then Puppeteer as fallback.
 */

