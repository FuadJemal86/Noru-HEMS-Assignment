const FLEXIBLE_EMAIL_PATTERN = /[A-Za-z0-9._%+-]{1,64}@[A-Za-z0-9.-]{1,255}\.[A-Za-z]{2,}/g;
const FINAL_EMAIL_VALIDATION = /^[a-z0-9._%+-]+@[a-z0-9.-]+\.[a-z]{2,}$/;
const TRAILING_WORDS = ["chat", "click", "email", "mail", "contact", "send", "message"];
const FALSE_POSITIVES = [
  "example.com", "test@example", "your-email", "email@example",
  "admin@localhost", "sentry.io", "wixpress.com", "u002f@", "u00", "http", "www.",
];

