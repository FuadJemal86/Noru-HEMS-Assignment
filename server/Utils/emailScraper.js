const INTERNAL_BRANCH_LOCAL_PATTERN = /^[a-z]{3,4}\d{2}$/;

/** Domain ending in file extensions = false positive (e.g. be_a_part_of_it@3x.jpg) */
const FILE_EXTENSION_TLD = /\.(jpg|jpeg|png|gif|svg|webp|pdf|ico|bmp)$/i;

